def test_every_lock_in_this_repository_records_a_command_that_writes_it() -> None:
    """The tool has one lock it cannot read, and the refresh stops at it."""
    requirements = REPOSITORY_ROOT / "requirements"
    if not requirements.is_dir():
        pytest.skip("requirements/ is repository content and this checkout has none")
    for path in sorted(requirements.glob("*.txt")):
        command = recorded_command(REPOSITORY_ROOT, path)
        source = input_of(command)
        assert (REPOSITORY_ROOT / source).is_file(), f"{path.name} compiles {source}, which is not here"
        assert "--universal" in command and "--generate-hashes" in command, path.name


# Dependabot and the CI job.


def workflow_document(path: Path) -> dict:
    if not path.is_file():
        pytest.skip(f"{path.name} is repository content and this checkout has none")
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def run_lines(job: dict) -> list[str]:
    lines = []
    for step in job.get("steps", []):
        for raw in step.get("run", "").splitlines():
            line = raw.strip()
            if line and not line.startswith("#"):
                lines.append(line)
    return lines


def test_dependabot_moves_the_locks_as_the_uv_ecosystem_and_not_as_pip() -> None:
    """The uv ecosystem reruns `uv pip compile` with the options each lock
    records; the pip ecosystem regenerated the .in-based locks through
    pip-compile, for one interpreter on one platform."""
    configuration = workflow_document(DEPENDABOT)
    entries = {entry["package-ecosystem"]: entry for entry in configuration["updates"]}

    assert "pip" not in entries
    assert entries["uv"]["directory"] == "/"
    assert entries["uv"]["groups"] == {"python-dependencies": {"patterns": ["*"]}}


def test_dependabot_leaves_pylink_square_below_the_ceiling_pyocd_sets() -> None:
    """dev.txt is edited pin by pin, and that edit crossed pyocd's `pylink-square<2.0`
    once; the ignore mirrors the ceiling the way the wrapt one mirrors python-can's."""
    configuration = workflow_document(DEPENDABOT)
    uv = next(entry for entry in configuration["updates"] if entry["package-ecosystem"] == "uv")
    ignored = {rule["dependency-name"]: rule["update-types"] for rule in uv["ignore"]}

    assert ignored["pylink-square"] == ["version-update:semver-major"]
    assert ignored["wrapt"] == ["version-update:semver-major"]


def test_the_lock_check_pins_its_actions_and_installs_uv_by_hash() -> None:
    job = workflow_document(CI_WORKFLOW)["jobs"]["lock_consistency"]
    lines = run_lines(job)
    installs = [line for line in lines if "pip install" in line]

    for step in job["steps"]:
        used = step.get("uses")
        assert used is None or PINNED_ACTION.match(used), used
    assert installs, lines
    assert all("--require-hashes" in line for line in installs), installs
    assert any("refresh_locks.py --uv-requirement" in line for line in lines), lines
    assert "python tools/refresh_locks.py --check" in lines


def test_the_lock_check_is_one_of_the_jobs_the_required_check_reads() -> None:
    workflow = workflow_document(CI_WORKFLOW)
    required = workflow["jobs"]["required-ci"]

    assert "lock_consistency" in required["needs"]
    assert "needs.lock_consistency.result" in required["steps"][0]["run"]
