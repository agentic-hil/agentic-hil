def test_every_lock_in_this_repository_records_a_command_that_writes_it() -> None:
    """The tool has one lock it cannot read, and the refresh stops at it."""
    requirements = REPOSITORY_ROOT / "requirements"
    if not requirements.is_dir():
        pytest.skip("requirements/ is repository content and this checkout has none")
    for path in sorted(requirements.glob("*.txt")):
        command = recorded_command(REPOSITORY_ROOT, path)
        source = input_of(command)
        assert (REPOSITORY_ROOT / source).is_file(), f"{path.name} compiles {source}, which is not here"
        assert "--universal" in command and "--generate-hashes" in command, path.name


# The workflows.


def workflow_document(path: Path) -> dict:
    if not path.is_file():
        pytest.skip(f"{path.name} is repository content and this checkout has none")
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def triggers(workflow: dict) -> dict:
    return workflow.get("on", workflow.get(True, {}))


def run_lines(job: dict) -> list[str]:
    lines = []
    for step in job.get("steps", []):
        for raw in step.get("run", "").splitlines():
            line = raw.strip()
            if line and not line.startswith("#"):
                lines.append(line)
    return lines


def refresh_job() -> dict:
    return workflow_document(REFRESH_WORKFLOW)["jobs"]["refresh"]


def test_dependabot_has_no_pip_entry_left_to_rewrite_the_locks_with() -> None:
    configuration = workflow_document(DEPENDABOT)

    assert [entry["package-ecosystem"] for entry in configuration["updates"]] == ["docker", "docker", "github-actions"]


def test_the_refresh_runs_on_a_schedule_and_on_request_and_on_nothing_else() -> None:
    assert set(triggers(workflow_document(REFRESH_WORKFLOW))) == {"workflow_dispatch", "schedule"}


def test_the_refresh_pins_every_action_by_commit() -> None:
    for workflow in (REFRESH_WORKFLOW, CI_WORKFLOW, REVIEW_WORKFLOW):
        for job in workflow_document(workflow)["jobs"].values():
            for step in job.get("steps", []):
                used = step.get("uses")
                assert used is None or PINNED_ACTION.match(used), f"{workflow.name} uses {used}"


def test_every_install_in_the_refresh_and_the_check_requires_hashes() -> None:
    """uv itself arrives by the hashes the container lock carries for it."""
    jobs = [refresh_job(), workflow_document(CI_WORKFLOW)["jobs"]["lock_consistency"]]
    for job in jobs:
        lines = run_lines(job)
        installs = [line for line in lines if "pip install" in line]
        assert installs, lines
        assert all("--require-hashes" in line for line in installs), installs
        assert any("refresh_locks.py --uv-requirement" in line for line in lines), lines


def test_the_refresh_runs_the_tool_and_hands_its_summary_to_the_pull_request() -> None:
    lines = run_lines(refresh_job())

    assert "python tools/refresh_locks.py --summary lock-refresh-summary.md" in lines
    assert any("gh pr create" in line and "--body-file lock-refresh-summary.md" in line for line in lines), lines
    assert any(line.startswith("git push --force origin") for line in lines), lines


def test_the_refresh_starts_the_checks_its_pull_request_never_gets_on_its_own() -> None:
    """A pull request opened with the workflow token starts no workflow.

    workflow_dispatch is the documented exception, so the refresh starts the
    required workflow and the dependency review on its branch by hand, and both
    have to be startable that way.
    """
    lines = run_lines(refresh_job())

    assert any(line.startswith("gh workflow run ci.yml --ref") for line in lines), lines
    assert any(line.startswith("gh workflow run dependency-review.yml --ref") for line in lines), lines
    assert "workflow_dispatch" in triggers(workflow_document(CI_WORKFLOW))
    assert "workflow_dispatch" in triggers(workflow_document(REVIEW_WORKFLOW))
    assert refresh_job()["permissions"]["actions"] == "write"


def test_the_dependency_review_compares_the_branch_with_master_when_started_by_hand() -> None:
    steps = workflow_document(REVIEW_WORKFLOW)["jobs"]["dependency-review"]["steps"]
    review = [step for step in steps if "dependency-review-action" in step.get("uses", "")]

    assert len(review) == 1
    assert "workflow_dispatch" in review[0]["with"]["base-ref"] and "'master'" in review[0]["with"]["base-ref"]
    assert "github.ref_name" in review[0]["with"]["head-ref"]


def test_the_lock_check_is_one_of_the_jobs_the_required_check_reads() -> None:
    workflow = workflow_document(CI_WORKFLOW)
    required = workflow["jobs"]["required-ci"]

    assert "lock_consistency" in required["needs"]
    assert "needs.lock_consistency.result" in required["steps"][0]["run"]
    assert "python tools/refresh_locks.py --check" in run_lines(workflow["jobs"]["lock_consistency"])
