def test_main_reports_the_check_on_stderr_and_exit_status(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    write_tree(tmp_path)
    rewritten = lock(
        "uv pip compile --generate-hashes --universal --python-version 3.12 requirements/container.in -o requirements/container.txt",
        "pyocd==0.46.0 \\\n    --hash=sha256:ff\n" + UV_HASHES,
    )

    assert main(["--check", "--root", str(tmp_path)], run=FakeUv(tmp_path)) == 0
    assert main(["--check", "--root", str(tmp_path)], run=FakeUv(tmp_path, rewrite={"requirements/container.txt": rewritten})) == 1
    assert "recompiling it moves pyocd 0.45.1 to 0.46.0" in capsys.readouterr().err


