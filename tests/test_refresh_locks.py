"""The lock files under requirements/ are written by one tool: the one whose
command each of them records.

Dependabot updated those files twice by moving pins one at a time, and both
times the result could not be installed: wrapt past the ceiling python-can
sets, then pylink-square past the one pyocd sets, the second time with the
markers that carry Windows and macOS packages dropped as well. Every
hash-pinned install in the matrix failed with ResolutionImpossible, and the
locks had to be regenerated by hand with the commands on their second lines.

What is pinned here is that the tool that replaced that reads those commands
and nothing else, that its refresh moves exact pins in the inputs and then
recompiles with --upgrade, that its check recompiles without --upgrade and
leaves the tree as it found it while naming the pins that moved, that the
workflows install uv by hash and pin every action by commit, that the weekly
refresh starts the checks its pull request would otherwise never get, and that
Dependabot no longer has a pip entry to do it the wrong way with.
"""

