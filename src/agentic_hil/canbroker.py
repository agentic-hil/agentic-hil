# Bumped whenever a message name, a field name or the meaning of a field moves.
# It seeds the connection counter, so a client built against another revision
# cannot present a counter a broker of this one would accept even by accident.
SURFACE_REVISION = 1
PROTOCOL_VERSION = 1

# The message surface itself, as data. The digest below is taken over it, so a
# field added, removed or renamed here changes what a cross-release peer is
# compared against — the digest cannot drift from the surface it describes,
# because it is computed from it rather than maintained beside it.
MESSAGE_SURFACE: dict[str, tuple[str, ...]] = {
    "attach": ("protocol_version", "protocol_digest", "expected_counter", "bus_key", "participant", "requires_listen_only", "client_pid"),
    "attached": ("ok", "counter", "broker_pid", "bus_key", "participant", "view", "bus_frame_log", "listen_only", "listen_only_enforcement", "listen_only_proof", "attached_participants"),
    "detach": (),
    "detached": ("ok", "participant", "attached_participants"),
    "send": ("frame",),
    "sent": ("ok", "frame_seq", "participant", "frame", "frames_used", "max_frames"),
    "read": ("max_frames", "wait_timeout_s"),
    "frames": ("ok", "frames", "frames_read", "frames_used", "max_frames"),
    "incident": ("scope", "reason", "detail"),
    "incident_recorded": ("ok", "scope", "reason", "bus_gated", "aborted_participants"),
    "poll_incident": (),
    "status": (),
    "bus_status": ("ok", "bus_key", "counter", "broker_pid", "attached_participants", "bus_gated", "frames_seen"),
    "frame": ("id", "extended", "rtr", "data_hex"),
    "abort": ("scope", "reason", "detail", "recovery_action", "at"),
}
PROTOCOL_DIGEST = hashlib.sha256(json.dumps(MESSAGE_SURFACE, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()[:16]

BROKER_DIRECTORY_NAME = "can-brokers"
DESCRIPTOR_VERSION = 1
AUTHKEY_BYTES = 32
