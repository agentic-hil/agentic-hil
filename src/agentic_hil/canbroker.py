"""One process owns one physical CAN bus; named participants share it.

CAN is a shared medium, and a ``can_buses`` entry has always modelled it as a
device with a single owner: ``can:<adapter>:<channel>`` is one exclusive,
machine-wide lock, so two runs on one bench serialise against each other even
when they are talking to two different devices on the same wire. This module is
the other half of that model, and it changes nothing about the first: a bus entry
with no ``shares:`` is still the single-owner bus it was, no broker is started
for it, and nothing here is on its path.

**The broker holds the same lock everybody else would have held.** It takes
``can:<adapter>:<channel>`` through the ordinary :class:`~agentic_hil.bench.BenchMutex`
and holds it for its whole life, so every exclusivity the single-owner model
enforced keeps being enforced — by one process, exactly once — and a single-owner
run on the same bench is refused by the bus being busy, as before. Participants
take *logical* locks ``<bus-key>#<name>``, so two runs may not share one
participant name while any number of distinctly named participants proceed in
parallel.

**Attaching proves the peer owns the bus, rather than asking it.** A broker's
claim to hold the lock is worth nothing on its own — a stale endpoint or an
impostor listener says the same words. So the attaching participant probes the
lock itself: it reads the holder record, checks that the pid there is the pid the
peer announced, and then *tries to take the bus lock*. Success is the refusal:
a lock this process could take is a lock the peer does not hold.

**Two staleness contracts, because they fail differently.** The protocol carries
a version and a digest of its own message surface, so a client and a broker from
different releases refuse each other at attach instead of misparsing frames
mid-run. The connection counter is the other one: it starts at the surface
revision, increments on every attach, and is published in the descriptor, so a
client attaching on a descriptor that has since moved on is refused cleanly with
both numbers named rather than acting on a picture of the bus that is out of
date.

**Local IPC only.** ``AF_UNIX`` on POSIX, a named pipe on Windows, never a
network listener. The HMAC authkey handshake in ``multiprocessing.connection``
runs before anything is unpickled, so an unauthenticated peer never reaches the
message loop. The key itself is generated by the broker, written beside the
descriptor with owner-only permissions, and deliberately kept out of every
structure this module builds: it is in no result, no report and no log line, and
``redact.redact_sensitive`` carries an ``authkey`` arm as the second line of that
defense rather than the first.
"""
