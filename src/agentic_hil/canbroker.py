# The participant side.


class ParticipantError(RuntimeError):
    """An attach that was refused, carrying the refusal a caller reports."""

    def __init__(self, result: JsonObject):
        super().__init__(str(result.get("summary", "CAN participant attach was refused.")))
        self.result = result


class Participant:
    """One run's named connection to a brokered bus.

    Keeps its own view of the traffic beside the broker's whole-bus log. Both
    carry the broker's frame sequence number, so a frame this participant sent is
    the same frame in the bus log — attributable from either end without either
    log having to be trusted about the other."""

    def __init__(self, config: AgenticHILConfig, bus_id: str, name: str, connection: Connection, attached: JsonObject, mutex: BenchMutex, lock_key: str, *, broker_process: subprocess.Popen | None = None):
        self.config = config
        self.bus_id = bus_id
        self.name = name
        self.connection = connection
        self.attached = attached
        self.mutex = mutex
        self.lock_key = lock_key
        self.broker_process = broker_process
        self.broker_pid = int(attached.get("broker_pid") or 0)
        self.counter = int(attached.get("counter") or 0)
        self.view = attached.get("view")
        self.bus_frame_log = attached.get("bus_frame_log")
        self.detached = False
        self.log_path = str(Path(logs_directory(config)) / f"can-participant-{timestamp_for_filename()}-{safe_filename(bus_id, 'bus')}-{safe_filename(name, 'participant')}.jsonl")
        with suppress(ConfigError, OSError):
            safe_append_text(self.log_path, "")
        self._log({"event": "attach", "bus_id": bus_id, "participant": name, "counter": self.counter, "broker_pid": self.broker_pid, "bus_frame_log": self.bus_frame_log, "view": self.view, "listen_only": attached.get("listen_only"), "listen_only_enforcement": attached.get("listen_only_enforcement"), "listen_only_proof": attached.get("listen_only_proof")})

    # -- operations --------------------------------------------------------

    def send(self, frame_id: int, data: bytes, *, extended: bool = False, rtr: bool = False) -> JsonObject:
        wire = frame_to_wire(frame_id, data, extended=extended, rtr=rtr)
        result = self._request({"message": "send", "frame": wire})
        self._log({"event": "frame", "direction": "tx", "participant": self.name, "frame_seq": result.get("frame_seq"), "frame": wire, "ok": bool(result.get("ok"))})
        return result

    def read(self, max_frames: int = 1, wait_timeout_s: float = 0.0) -> JsonObject:
        result = self._request({"message": "read", "max_frames": max_frames, "wait_timeout_s": wait_timeout_s})
        for frame in result.get("frames", []) if isinstance(result.get("frames"), list) else []:
            self._log({"event": "frame", "direction": "rx", "participant": self.name, "frame_seq": frame.get("frame_seq"), "frame": {key: value for key, value in frame.items() if key != "frame_seq"}, "ok": True})
        return result

    def report_incident(self, scope: str, reason: str, detail: object = None) -> JsonObject:
        result = self._request({"message": "incident", "scope": scope, "reason": reason, "detail": detail})
        self._log({"event": "incident", "scope": scope, "reason": reason, "participant": self.name, "bus_gated": result.get("bus_gated")})
        return result

    def poll_incident(self) -> JsonObject:
        return self._request({"message": "poll_incident"})

    def status(self) -> JsonObject:
        return self._request({"message": "status"})

    def detach(self) -> JsonObject:
        if self.detached:
            return {"ok": True, "message": "detached", "participant": self.name, "already_detached": True}
        self.detached = True
        result: JsonObject = {"ok": True, "message": "detached", "participant": self.name}
        try:
            result = self._request({"message": "detach"})
        except (OSError, EOFError, ParticipantError):
            result = {"ok": True, "message": "detached", "participant": self.name, "broker_unreachable": True}
        finally:
            with suppress(BaseException):
                self.connection.close()
            self._log({"event": "detach", "participant": self.name, "attached_participants": result.get("attached_participants")})
            with suppress(BaseException):
                self.mutex.release_all()
        return result

    def __enter__(self) -> Participant:
        return self

    def __exit__(self, *_: object) -> None:
        self.detach()

    # -- plumbing ----------------------------------------------------------

    def _request(self, payload: JsonObject) -> JsonObject:
        self.connection.send(payload)
        if not self.connection.poll(CLIENT_REQUEST_TIMEOUT_S):
            raise ParticipantError({"ok": False, "error_type": "can_broker_timeout", "summary": "The CAN broker did not answer within the request timeout.", "bus_id": self.bus_id, "participant": self.name, "side_effect_status": "unknown"})
        answer = self.connection.recv()
        if not isinstance(answer, dict):
            raise ParticipantError({"ok": False, "error_type": "can_broker_invalid_message", "summary": "The CAN broker answered with a message this client cannot read.", "bus_id": self.bus_id, "participant": self.name})
        return answer

    def _log(self, event: JsonObject) -> None:
        with suppress(ConfigError, OSError, ValueError):
            safe_append_text(self.log_path, json.dumps({"at": utc_now_iso(), **event}) + "\n")


def attach_participant(
    config: AgenticHILConfig,
    bus_id: str,
    participant: str,
    *,
    mutex: BenchMutex | None = None,
    wait_s: float = 0.0,
    start_timeout_s: float = BROKER_START_TIMEOUT_S,
    allow_start: bool = True,
) -> Participant:
    """Attach this run to a named participant view, starting the broker if needed.

    Order matters and is the point. The participant lock is taken *first*, so a
    second run claiming the same name is refused by the ordinary bench mutex
    before any broker is spoken to and whether or not one is running. Then the
    broker is found or started, and only then is the peer believed — after the
    lock probe says it is the process holding the bus."""
    bus_config = config.can_buses.get(bus_id)
    if bus_config is None:
        raise ParticipantError({"ok": False, "error_type": "can_bus_not_configured", "summary": "CAN bus is not available in the authoritative config.", "bus_id": bus_id, "configured_buses": sorted(config.can_buses)})
    if not bus_config.shares:
        raise ParticipantError({"ok": False, "error_type": "can_bus_not_shared", "summary": "This CAN bus declares no shares:, so it is a single-owner bus and has no participants.", "bus_id": bus_id})
    if participant not in bus_config.shares:
        raise ParticipantError({"ok": False, "error_type": "can_participant_not_configured", "summary": "The authoritative config declares no such participant view on this CAN bus.", "bus_id": bus_id, "participant": participant, "configured_participants": sorted(bus_config.shares)})
    try:
        bus_key = bus_lock_key(config, bus_id)
    except DeviceError as error:
        raise ParticipantError(error.result) from error
    owner = mutex or BenchMutex(frontend="can-participant", label=f"can-participant:{bus_id}#{participant}")
    lock_key = participant_lock_key(bus_key, participant)
    try:
        owner.acquire_named(lock_key, wait_s=wait_s)
    except DeviceBusyError as error:
        raise ParticipantError({**error.result, "bus_id": bus_id, "participant": participant, "participant_lock": lock_key, "summary": f"CAN participant '{participant}' on bus '{bus_id}' is already held by another run; two runs may not share one participant name."}) from error
    try:
        return _attach_with_broker(config, bus_id, participant, bus_key, owner, lock_key, start_timeout_s, allow_start)
    except BaseException:
        with suppress(BaseException):
            owner.release_all()
        raise


def _attach_with_broker(config: AgenticHILConfig, bus_id: str, participant: str, bus_key: str, owner: BenchMutex, lock_key: str, start_timeout_s: float, allow_start: bool) -> Participant:
    lock_root = owner.root
    deadline = time.monotonic() + start_timeout_s
    started: subprocess.Popen | None = None
    last: JsonObject = {"ok": False, "error_type": "can_broker_unavailable", "summary": "No CAN broker for this bus could be reached or started.", "bus_id": bus_id, "bus_key": bus_key}
    attempts = 0
    while time.monotonic() < deadline:
        descriptor = read_descriptor(bus_key, lock_root)
        if descriptor is not None:
            attempts += 1
            outcome = _attach_once(config, bus_id, participant, bus_key, descriptor, owner, lock_key, lock_root, started)
            if isinstance(outcome, Participant):
                return outcome
            last = outcome
            if outcome.get("error_type") == "can_broker_counter_mismatch" and attempts <= ATTACH_COUNTER_RETRIES:
                time.sleep(BROKER_POLL_INTERVAL_S)
                continue
            if allow_start and outcome.get("error_type") == "can_broker_not_bus_owner" and outcome.get("bus_lock_held") is False:
                # A descriptor whose bus lock is free is a broker that was killed
                # before it could clean up after itself: `shutdown` removes the
                # descriptor *before* releasing the lock, so the two states can
                # only be seen together when nothing ran the cleanup at all.
                #
                # Refusing here would let one hard-killed broker brick the bus
                # until somebody deleted a file by hand. Removing the corpse is
                # safe precisely because the probe already failed: the endpoint
                # behind it owns nothing, so nothing is taken from anybody — and
                # an impostor's planted descriptor gets the same treatment,
                # having never been spoken to. When starting a broker is not
                # allowed there is nothing to replace it with, so the refusal
                # stands and the caller is told the peer is not the bus owner.
                _remove_stale_broker(bus_key, lock_root)
                continue
            if outcome.get("retry_safe") is not True:
                raise ParticipantError(outcome)
            time.sleep(BROKER_POLL_INTERVAL_S)
            continue
        if not allow_start:
            raise ParticipantError({**last, "error_type": "can_broker_unavailable", "summary": "No CAN broker is running for this bus and starting one was not allowed."})
        if started is None or started.poll() is not None:
            if started is not None and started.poll() == BROKER_EXIT_BUS_BUSY:
                # Somebody else owns the physical bus: either the broker that won
                # the start race, whose descriptor is about to appear, or a
                # single-owner run, in which case the deadline is the refusal.
                started = None
                time.sleep(BROKER_POLL_INTERVAL_S)
                continue
            started = _spawn_broker(config, bus_id, bus_key, lock_root)
        time.sleep(BROKER_POLL_INTERVAL_S)
    if started is not None and started.poll() is None:
        with suppress(BaseException):
            started.terminate()
    raise ParticipantError(last)


def _attach_once(config: AgenticHILConfig, bus_id: str, participant: str, bus_key: str, descriptor: BrokerDescriptor, owner: BenchMutex, lock_key: str, lock_root: Path, started: subprocess.Popen | None) -> Participant | JsonObject:
    if descriptor.protocol_version != PROTOCOL_VERSION or descriptor.protocol_digest != PROTOCOL_DIGEST:
        return {
            "ok": False,
            "error_type": "can_broker_protocol_mismatch",
            "summary": "The CAN broker running for this bus was built from a different release of the broker protocol.",
            "bus_id": bus_id,
            "broker_protocol_version": descriptor.protocol_version,
            "client_protocol_version": PROTOCOL_VERSION,
            "broker_protocol_digest": descriptor.protocol_digest,
            "client_protocol_digest": PROTOCOL_DIGEST,
            "retry_safe": False,
            "side_effect_committed": False,
        }
    probe = probe_bus_lock(bus_key, descriptor.pid, lock_root)
    if not probe["ok"]:
        return {**probe, "bus_id": bus_id, "participant": participant}
    key = _read_authkey(authkey_path(bus_key, lock_root))
    if key is None:
        return {"ok": False, "error_type": "can_broker_unavailable", "summary": "The CAN broker published no authentication key beside its descriptor.", "bus_id": bus_id, "retry_safe": True, "side_effect_committed": False}
    try:
        connection = Client(descriptor.endpoint, descriptor.family, authkey=key)
    except AuthenticationError as error:
        return {"ok": False, "error_type": "can_broker_authentication_failed", "summary": "The CAN broker refused this client's authentication key.", "bus_id": bus_id, "backend_error": str(error), "retry_safe": False, "side_effect_committed": False}
    except (FileNotFoundError, ConnectionRefusedError, OSError) as error:
        return {"ok": False, "error_type": "can_broker_unavailable", "summary": "The CAN broker endpoint could not be reached.", "bus_id": bus_id, "backend_error": str(error), "retry_safe": True, "side_effect_committed": False}
    try:
        connection.send(
            {
                "message": "attach",
                "protocol_version": PROTOCOL_VERSION,
                "protocol_digest": PROTOCOL_DIGEST,
                "expected_counter": descriptor.counter,
                "bus_key": bus_key,
                "participant": participant,
                "requires_listen_only": config.can_buses[bus_id].shares[participant].requires_listen_only,
                "client_pid": os.getpid(),
            }
        )
        if not connection.poll(CLIENT_REQUEST_TIMEOUT_S):
            raise TimeoutError("The CAN broker did not answer the attach request.")
        answer = connection.recv()
    except BaseException as error:
        with suppress(BaseException):
            connection.close()
        return {"ok": False, "error_type": "can_broker_unavailable", "summary": "The CAN broker did not complete the attach handshake.", "bus_id": bus_id, "backend_error": f"{type(error).__name__}: {error}", "retry_safe": True, "side_effect_committed": False}
    if not isinstance(answer, dict) or not answer.get("ok"):
        with suppress(BaseException):
            connection.close()
        refusal = answer if isinstance(answer, dict) else {"ok": False, "error_type": "can_broker_invalid_message", "summary": "The CAN broker answered the attach with a message this client cannot read."}
        return {**refusal, "bus_id": bus_id, "participant": participant}
    return Participant(config, bus_id, participant, connection, answer, owner, lock_key, broker_process=started)


def _spawn_broker(config: AgenticHILConfig, bus_id: str, bus_key: str, lock_root: Path) -> subprocess.Popen:
    """Start a broker for this bus, detached from the run that started it.

    :func:`~agentic_hil.process.spawn_detached_process` rather than
    ``spawn_managed_process``, and the difference is the whole reason the broker
    is spawned through the detached name: a managed child joins a kill-on-close
    Job Object owned by this run, and a broker that died with whichever run
    happened to attach first would not be a shared bus — the second participant
    would lose the medium because the first one's run ended. The broker's
    lifetime is bounded by its own rules instead: the last participant
    detaching, and the first-attach deadline below.

    Losing the race for the bus lock is a clean exit, not an error — the
    winner's descriptor is what the loser's client then finds.

    The first-attach deadline travels on the command line rather than being read
    from this module in the child. A constant read in the child is a constant a
    caller cannot influence, and a test that sets it here would be quietly
    testing nothing."""
    # The child's diagnostics go to a file rather than to a pipe: nobody is left
    # reading a broker's stderr once the run that started it has moved on, and a
    # full pipe would block the broker mid-bus.
    with open(broker_log_path(bus_key, lock_root), "ab") as handle:
        return spawn_detached_process(
            [
                sys.executable,
                "-m",
                "agentic_hil.canbroker",
                "--workspace-root",
                str(config.work_dir),
                "--bus-id",
                bus_id,
                "--first-attach-timeout-s",
                str(BROKER_FIRST_ATTACH_TIMEOUT_S),
            ],
            stdin=subprocess.DEVNULL,
            stdout=handle,
            stderr=handle,
            cwd=str(config.work_dir),
        )


# ---------------------------------------------------------------------------
# The broker process entry point.


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="agentic-hil-can-broker", description="Own one physical CAN bus for its named participants.")
    parser.add_argument("--workspace-root", required=True)
    parser.add_argument("--bus-id", required=True)
    parser.add_argument("--first-attach-timeout-s", type=float, default=BROKER_FIRST_ATTACH_TIMEOUT_S)
    arguments = parser.parse_args(argv)
    try:
        config = load_authoritative_config(arguments.workspace_root)
    except ConfigError as error:
        print(json.dumps({"ok": False, "error_type": error.error_type, "summary": str(error)}), file=sys.stderr)
        return BROKER_EXIT_CONFIG
    bus_config = config.can_buses.get(arguments.bus_id)
    if bus_config is None or not bus_config.shares:
        print(json.dumps({"ok": False, "error_type": "can_bus_not_shared", "summary": "The authoritative config declares no shared CAN bus of that name.", "bus_id": arguments.bus_id}), file=sys.stderr)
        return BROKER_EXIT_CONFIG
    broker = CanBroker(config, arguments.bus_id)
    try:
        broker.take_bus()
    except DeviceBusyError as error:
        print(json.dumps({"ok": False, "error_type": "device_busy", "summary": str(error), "bus_key": broker.bus_key}), file=sys.stderr)
        return BROKER_EXIT_BUS_BUSY
    try:
        opened = broker.open_bus()
        if not opened.get("ok"):
            print(json.dumps(opened, default=str), file=sys.stderr)
            return BROKER_EXIT_ADAPTER
        broker.publish()
        return broker.serve(arguments.first_attach_timeout_s)
    finally:
        broker.shutdown()


if __name__ == "__main__":
    raise SystemExit(main())
