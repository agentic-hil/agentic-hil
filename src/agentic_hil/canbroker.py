# Names, addresses and the rendezvous on disk.


def bus_lock_key(config: AgenticHILConfig, bus_id: str) -> str:
    """The machine-wide lock a broker for this bus takes, spelled as the device spells it."""
    return can_device(config, bus_id).lock_key


def participant_lock_key(bus_key: str, participant: str) -> str:
    """The logical lock one named participant takes: ``<bus-key>#<name>``.

    Folded through the same rule as the bus key, so a participant cannot be
    split from itself by spelling."""
    return fold_resource_name(f"{bus_key}#{participant}")


def _broker_home(lock_root: Path) -> Path:
    """Where a broker publishes itself: beside the device locks it holds.

    Derived from the lock root rather than from the home directory again, so a
    broker and the lock it takes cannot end up in two different places — which is
    the split ``bench.device_lock_root`` exists to prevent for locks."""
    return safe_directory(lock_root.parent / BROKER_DIRECTORY_NAME)


def descriptor_path(bus_key: str, lock_root: Path) -> Path:
    return _broker_home(lock_root) / f"{resource_digest(bus_key)}.broker.json"


def authkey_path(bus_key: str, lock_root: Path) -> Path:
    return _broker_home(lock_root) / f"{resource_digest(bus_key)}.authkey"


def broker_log_path(bus_key: str, lock_root: Path) -> Path:
    return _broker_home(lock_root) / f"{resource_digest(bus_key)}.broker.log"


def endpoint_family() -> str:
    return "AF_PIPE" if os.name == "nt" else "AF_UNIX"


def endpoint_address(bus_key: str, lock_root: Path) -> str:
    """The local IPC address for this bus, on this lock root.

    Deliberately *not* under the lock root on POSIX. An ``AF_UNIX`` path is
    capped near 108 bytes by the kernel, and the lock root follows the user's
    home — under a test sandbox or a long profile name a socket there simply
    cannot be bound, and the failure would arrive as a truncated path rather than
    as anything readable. The address is published in the descriptor, so it does
    not have to be derivable by anyone; it only has to be short, per user, and
    distinct per lock root, which is what the tag is."""
    tag = hashlib.sha256(f"{os.path.normcase(str(lock_root))}\0{bus_key}".encode()).hexdigest()[:20]
    if os.name == "nt":
        return rf"\\.\pipe\agentic-hil-can-{tag}"
    directory = Path(tempfile.gettempdir()) / f"agentic-hil-can-{os.getuid()}"
    directory.mkdir(mode=0o700, exist_ok=True)
    entry = os.stat(directory)
    if entry.st_uid != os.getuid() or not stat.S_ISDIR(entry.st_mode):
        raise ConfigError("config_invalid", "The CAN broker socket directory is not owned by this user.", {"path": str(directory)})
    os.chmod(directory, 0o700)
    return str(directory / f"{tag}.sock")


@dataclass(frozen=True)
class BrokerDescriptor:
    """What a running broker publishes about itself.

    Carries no authkey, by construction: this record is JSON on disk and is
    copied into refusals, and the one thing that must never be in a JSON
    structure is the key. The key lives in a sibling file with owner-only
    permissions and is read as bytes."""

    bus_key: str
    endpoint: str
    family: str
    pid: int
    protocol_version: int
    protocol_digest: str
    counter: int
    started_at: str

    def as_json(self) -> JsonObject:
        return {
            "version": DESCRIPTOR_VERSION,
            "bus_key": self.bus_key,
            "endpoint": self.endpoint,
            "family": self.family,
            "pid": self.pid,
            "protocol_version": self.protocol_version,
            "protocol_digest": self.protocol_digest,
            "counter": self.counter,
            "started_at": self.started_at,
        }

    @staticmethod
    def from_json(value: object) -> BrokerDescriptor | None:
        if not isinstance(value, dict) or value.get("version") != DESCRIPTOR_VERSION:
            return None
        try:
            return BrokerDescriptor(
                bus_key=str(value["bus_key"]),
                endpoint=str(value["endpoint"]),
                family=str(value["family"]),
                pid=int(value["pid"]),
                protocol_version=int(value["protocol_version"]),
                protocol_digest=str(value["protocol_digest"]),
                counter=int(value["counter"]),
                started_at=str(value["started_at"]),
            )
        except (KeyError, TypeError, ValueError):
            return None


def read_descriptor(bus_key: str, lock_root: Path) -> BrokerDescriptor | None:
    try:
        text = safe_read_text(descriptor_path(bus_key, lock_root))
    except (FileNotFoundError, OSError, UnicodeDecodeError, ConfigError):
        return None
    try:
        return BrokerDescriptor.from_json(json.loads(text))
    except ValueError:
        return None


def _remove_stale_broker(bus_key: str, lock_root: Path) -> None:
    """Clear the rendezvous of a broker that is provably not on the bus.

    Only ever called after a lock probe has shown the bus lock free, which is the
    one state a live broker cannot be in: it holds that lock from before it
    publishes until after it unpublishes. The authkey goes with the descriptor
    because a key without an endpoint authenticates nothing."""
    for path in (descriptor_path(bus_key, lock_root), authkey_path(bus_key, lock_root)):
        with suppress(FileNotFoundError, OSError):
            os.unlink(path)


def _write_authkey(path: Path, key: bytes) -> None:
    """Write the HMAC key owner-only, replacing whatever was there.

    ``os.open`` with an explicit mode rather than a text write, because the mode
    has to be on the file from the moment it exists — a chmod afterwards is a
    window. On Windows the mode bits are advisory; what protects the file there
    is that it lives under the user's own profile, the same argument the device
    locks beside it rest on."""
    with suppress(FileNotFoundError):
        os.unlink(path)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0), 0o600)
    try:
        os.write(descriptor, key)
    finally:
        os.close(descriptor)


def _read_authkey(path: Path) -> bytes | None:
    try:
        with open(path, "rb") as handle:
            key = handle.read(AUTHKEY_BYTES * 2)
    except OSError:
        return None
    return key or None


# ---------------------------------------------------------------------------
# The lock probe: the peer holds the bus, or it does not.


def probe_bus_lock(bus_key: str, expected_pid: int, lock_root: Path) -> JsonObject:
    """Whether the process at ``expected_pid`` really holds this bus lock.

    Three questions, and the third is the one that cannot be faked. The holder
    record must exist and name that pid on this host — but the record is
    advisory, so an impostor could have written it. The lock itself is not: a
    lock this process can take is a lock nobody holds. So the probe *tries to
    acquire* the bus lock non-blocking, and treats success as the refusal.

    Nothing is written on the way through. A successful probe acquisition is
    released immediately and never leaves a holder record, so a probe cannot be
    mistaken for an owner by the next contender."""
    record_path = lock_root / f"{resource_digest(bus_key)}.holder.json"
    record: JsonObject | None = None
    try:
        record = json.loads(safe_read_text(record_path))
    except (FileNotFoundError, OSError, UnicodeDecodeError, ConfigError, ValueError):
        record = None
    owner = record.get("owner") if isinstance(record, dict) and isinstance(record.get("owner"), dict) else None
    probe = _LifetimeLock(lock_root / f"{resource_digest(bus_key)}.lock")
    try:
        probe.acquire()
    except (BlockingIOError, OSError):
        held = True
    else:
        held = False
        with suppress(BaseException):
            probe.release()
    if not held:
        return {
            "ok": False,
            "error_type": "can_broker_not_bus_owner",
            "summary": "The CAN broker endpoint does not hold this bus lock; the bus lock was free while it claimed to own the bus.",
            "bus_key": bus_key,
            "claimed_broker_pid": expected_pid,
            "bus_lock_held": False,
            "retry_safe": False,
            "side_effect_committed": False,
        }
    if owner is None or record is None or record.get("state") != "held":
        return {
            "ok": False,
            "error_type": "can_broker_not_bus_owner",
            "summary": "The CAN bus lock is held, but no holder record identifies the process holding it as the broker that answered.",
            "bus_key": bus_key,
            "claimed_broker_pid": expected_pid,
            "bus_lock_held": True,
            "retry_safe": True,
            "side_effect_committed": False,
        }
    if owner.get("pid") != expected_pid or owner.get("host") != socket.gethostname():
        return {
            "ok": False,
            "error_type": "can_broker_not_bus_owner",
            "summary": "The CAN bus lock is held by a different process than the endpoint that answered.",
            "bus_key": bus_key,
            "claimed_broker_pid": expected_pid,
            "bus_lock_holder": {"pid": owner.get("pid"), "host": owner.get("host")},
            "bus_lock_held": True,
            "retry_safe": False,
            "side_effect_committed": False,
        }
    return {"ok": True, "bus_key": bus_key, "broker_pid": expected_pid, "bus_lock_held": True}


