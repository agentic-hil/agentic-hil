# The broker.


@dataclass
class _Attached:
    name: str
    share: CanShareConfig
    connection: Connection
    client_pid: int
    attached_at: str
    frames_used: int = 0
    queue: list[JsonObject] = field(default_factory=list)
    abort: JsonObject | None = None


class CanBroker:
    """One process, one physical bus, many named participants.

    Owns the bus lock and the adapter for its whole life. Everything a
    participant does to the medium passes through here, which is what makes the
    whole-bus frame log complete: the broker is the only writer, so a frame in a
    participant's own log is a frame in this one, under the same sequence
    number."""

    def __init__(self, config: AgenticHILConfig, bus_id: str, *, mutex: BenchMutex | None = None):
        self.config = config
        self.bus_id = bus_id
        self.bus_config = config.can_buses[bus_id]
        self.mutex = mutex or BenchMutex(frontend="can-broker", label=f"can-broker:{bus_id}")
        self.bus_key = bus_lock_key(config, bus_id)
        self.lock_root = self.mutex.root
        self.counter = SURFACE_REVISION
        self.attach_total = 0
        self.frame_seq = 0
        self.bus_gated = False
        self.bus_incident: JsonObject | None = None
        self.participants: dict[str, _Attached] = {}
        self.adapter_session: object | None = None
        self.bus_frame_log = ""
        self._guard = threading.RLock()
        self._stopping = threading.Event()
        self._listener: Listener | None = None
        self._authkey = secrets.token_bytes(AUTHKEY_BYTES)
        self._endpoint = ""
        self._started_at = utc_now_iso()

    # -- lifecycle ---------------------------------------------------------

    def take_bus(self) -> None:
        """Hold the machine-wide bus lock for this broker's whole life."""
        self.mutex.acquire_named(self.bus_key)

    def open_bus(self) -> JsonObject:
        from agentic_hil.can import open_adapter

        self.bus_frame_log = str(Path(logs_directory(self.config)) / f"can-bus-{timestamp_for_filename()}-{safe_filename(self.bus_id, 'bus')}.jsonl")
        safe_append_text(self.bus_frame_log, "")
        opened = open_adapter(self.config, self.bus_id, self.bus_config, False)
        if not opened.get("ok"):
            return {key: value for key, value in opened.items() if key != "session"}
        self.adapter_session = opened["session"]
        self._log_bus({"event": "broker_start", "bus_id": self.bus_id, "bus_key": self.bus_key, "adapter": self.bus_config.adapter, "channel": self.bus_config.channel, "listen_only": self.bus_config.listen_only, "listen_only_enforcement": self.bus_config.listen_only_enforcement, "listen_only_proof": listen_only_proof(self.bus_config), "broker_pid": os.getpid()})
        return {"ok": True}

    def publish(self) -> None:
        self._endpoint = endpoint_address(self.bus_key, self.lock_root)
        if os.name != "nt":
            # The bus lock is already ours, so no other broker for this bus can
            # exist and a socket file here is the corpse of one the OS reaped.
            with suppress(FileNotFoundError):
                os.unlink(self._endpoint)
        self._listener = Listener(self._endpoint, endpoint_family(), authkey=self._authkey)
        _write_authkey(authkey_path(self.bus_key, self.lock_root), self._authkey)
        self._write_descriptor()

    def _write_descriptor(self) -> None:
        descriptor = BrokerDescriptor(
            bus_key=self.bus_key,
            endpoint=self._endpoint,
            family=endpoint_family(),
            pid=os.getpid(),
            protocol_version=PROTOCOL_VERSION,
            protocol_digest=PROTOCOL_DIGEST,
            counter=self.counter,
            started_at=self._started_at,
        )
        atomic_write_text(descriptor_path(self.bus_key, self.lock_root), json.dumps(descriptor.as_json(), indent=2) + "\n")

    def serve(self, first_attach_timeout_s: float = BROKER_FIRST_ATTACH_TIMEOUT_S) -> int:
        """Accept participants until the last one detaches.

        The first-attach deadline is not tidiness: a client that spawned a broker
        and then died before attaching would otherwise leave a process sitting on
        the bus lock with nobody able to say why, which is exactly the orphan the
        automatic lifecycle exists to avoid."""
        assert self._listener is not None
        deadline = time.monotonic() + first_attach_timeout_s
        handlers: list[threading.Thread] = []
        waiter = threading.Thread(target=self._first_attach_watchdog, args=(deadline,), daemon=True)
        waiter.start()
        while not self._stopping.is_set():
            try:
                connection = self._listener.accept()
            except (AuthenticationError, OSError):
                continue
            except BaseException:
                break
            if self._stopping.is_set():
                with suppress(BaseException):
                    connection.close()
                break
            handler = threading.Thread(target=self._serve_connection, args=(connection,), daemon=True)
            handler.start()
            handlers.append(handler)
            handlers = [item for item in handlers if item.is_alive()]
        for handler in handlers:
            handler.join(timeout=5.0)
        return BROKER_EXIT_OK

    def _first_attach_watchdog(self, deadline: float) -> None:
        while not self._stopping.is_set() and time.monotonic() < deadline:
            with self._guard:
                if self.attach_total:
                    return
            time.sleep(BROKER_POLL_INTERVAL_S)
        with self._guard:
            if self.attach_total:
                return
        self.stop("no_participant_attached")

    def stop(self, reason: str) -> None:
        if self._stopping.is_set():
            return
        self._stopping.set()
        self._log_bus({"event": "broker_stop", "bus_id": self.bus_id, "reason": reason, "frames_seen": self.frame_seq})
        # `accept()` is blocked in the serve loop; a throwaway connection is what
        # wakes it, and it is authenticated like any other so the wake cannot come
        # from outside.
        with suppress(BaseException):
            Client(self._endpoint, endpoint_family(), authkey=self._authkey).close()

    def shutdown(self) -> None:
        with suppress(BaseException):
            if self._listener is not None:
                self._listener.close()
        session = self.adapter_session
        if session is not None:
            with suppress(BaseException):
                session.close()  # type: ignore[attr-defined]
            self.adapter_session = None
        for path in (descriptor_path(self.bus_key, self.lock_root), authkey_path(self.bus_key, self.lock_root)):
            with suppress(FileNotFoundError, OSError):
                os.unlink(path)
        if os.name != "nt" and self._endpoint:
            with suppress(FileNotFoundError, OSError):
                os.unlink(self._endpoint)
        with suppress(BaseException):
            self.mutex.release_all()

    # -- connections -------------------------------------------------------

    def _serve_connection(self, connection: Connection) -> None:
        attached: _Attached | None = None
        try:
            while True:
                try:
                    message = connection.recv()
                except (EOFError, OSError):
                    break
                if not isinstance(message, dict):
                    self._reply(connection, {"ok": False, "error_type": "can_broker_invalid_message", "summary": "The CAN broker received a message it cannot read."})
                    break
                kind = message.get("message")
                if attached is None:
                    if kind != "attach":
                        self._reply(connection, {"ok": False, "error_type": "can_broker_not_attached", "summary": "The first CAN broker message must be an attach."})
                        break
                    reply, attached = self._handle_attach(message, connection)
                    self._reply(connection, reply)
                    if attached is None:
                        break
                    continue
                if kind == "detach":
                    self._reply(connection, self._handle_detach(attached))
                    attached = None
                    break
                self._reply(connection, self._handle_request(attached, kind, message))
        finally:
            with suppress(BaseException):
                connection.close()
            if attached is not None:
                # A participant whose process died without detaching must not keep
                # the bus. The connection closing is the detach.
                self._detach(attached, "connection_closed")

    def _reply(self, connection: Connection, payload: JsonObject) -> None:
        with suppress(OSError, EOFError):
            connection.send(payload)

    # -- attach ------------------------------------------------------------

    def _handle_attach(self, message: JsonObject, connection: Connection) -> tuple[JsonObject, _Attached | None]:
        with self._guard:
            if message.get("protocol_version") != PROTOCOL_VERSION or message.get("protocol_digest") != PROTOCOL_DIGEST:
                return {
                    "ok": False,
                    "error_type": "can_broker_protocol_mismatch",
                    "summary": "The CAN broker and this client were built from different releases of the broker protocol.",
                    "broker_protocol_version": PROTOCOL_VERSION,
                    "client_protocol_version": message.get("protocol_version"),
                    "broker_protocol_digest": PROTOCOL_DIGEST,
                    "client_protocol_digest": message.get("protocol_digest"),
                    "retry_safe": False,
                    "side_effect_committed": False,
                }, None
            if message.get("expected_counter") != self.counter:
                return {
                    "ok": False,
                    "error_type": "can_broker_counter_mismatch",
                    "summary": "The CAN broker connection counter has moved on since this client read the broker descriptor.",
                    "broker_counter": self.counter,
                    "client_counter": message.get("expected_counter"),
                    "retry_safe": True,
                    "side_effect_committed": False,
                }, None
            if message.get("bus_key") != self.bus_key:
                return {"ok": False, "error_type": "can_broker_wrong_bus", "summary": "The CAN broker endpoint owns a different bus than the client asked for.", "broker_bus_key": self.bus_key, "client_bus_key": message.get("bus_key"), "retry_safe": False, "side_effect_committed": False}, None
            if self.bus_gated:
                return {"ok": False, "error_type": "can_bus_gated", "summary": "The CAN bus is gated by a bus-scoped incident and accepts no further participants.", "bus_key": self.bus_key, "incident": self.bus_incident, "retry_safe": False, "side_effect_committed": False}, None
            name = message.get("participant")
            if not isinstance(name, str) or name not in self.bus_config.shares:
                return {"ok": False, "error_type": "can_participant_not_configured", "summary": "The authoritative config declares no such participant view on this CAN bus.", "bus_id": self.bus_id, "participant": name, "configured_participants": sorted(self.bus_config.shares), "retry_safe": False, "side_effect_committed": False}, None
            if name in self.participants:
                return {"ok": False, "error_type": "can_participant_busy", "summary": "A participant of that name is already attached to this CAN bus.", "bus_key": self.bus_key, "participant": name, "retry_safe": True, "side_effect_committed": False}, None
            share = self.bus_config.shares[name]
            conflict = self._listen_only_conflict(name, share)
            if conflict is not None:
                return conflict, None
            self.counter += 1
            self.attach_total += 1
            attached = _Attached(name=name, share=share, connection=connection, client_pid=int(message.get("client_pid") or 0), attached_at=utc_now_iso())
            self.participants[name] = attached
            with suppress(ConfigError, OSError):
                self._write_descriptor()
            self._log_bus({"event": "participant_attach", "bus_id": self.bus_id, "participant": name, "counter": self.counter, "client_pid": attached.client_pid, "view": share_view(share)})
            return {
                "ok": True,
                "message": "attached",
                "counter": self.counter,
                "broker_pid": os.getpid(),
                "bus_key": self.bus_key,
                "bus_id": self.bus_id,
                "participant": name,
                "view": share_view(share),
                "bus_frame_log": display_path(self.config, self.bus_frame_log),
                "listen_only": self.bus_config.listen_only,
                "listen_only_enforcement": self.bus_config.listen_only_enforcement,
                "listen_only_proof": listen_only_proof(self.bus_config),
                "attached_participants": sorted(self.participants),
            }, attached

    def _listen_only_conflict(self, name: str, share: CanShareConfig) -> JsonObject | None:
        """Listen-only is a property of the bus, so the two kinds cannot coexist.

        The flag stands for a controller-level proof, and a controller has one
        state for the whole medium — not one per acceptance filter. So a
        participant that needs the bus silent and a participant that transmits
        are refused against each other rather than both being seated and one of
        them being quietly wrong. The enforcement level is named in the refusal
        because it is what the refusal is worth: at ``service`` the guarantee
        would have been software filtering, and saying so is the point of the
        key."""
        common = {
            "error_type": "can_listen_only_conflict",
            "bus_id": self.bus_id,
            "bus_key": self.bus_key,
            "participant": name,
            "listen_only": self.bus_config.listen_only,
            "listen_only_enforcement": self.bus_config.listen_only_enforcement,
            "listen_only_proof": listen_only_proof(self.bus_config),
            "retry_safe": False,
            "side_effect_committed": False,
            "ok": False,
        }
        if share.permissions.allow_write and self.bus_config.listen_only:
            return {**common, "summary": "This CAN bus is configured listen_only, so a participant that may transmit cannot attach to it.", "conflicting_participants": []}
        writers = sorted(other for other, item in self.participants.items() if item.share.permissions.allow_write)
        listeners = sorted(other for other, item in self.participants.items() if item.share.requires_listen_only)
        if share.requires_listen_only and writers:
            return {**common, "summary": "A participant that requires a listen-only bus cannot attach while a transmitting participant is attached.", "conflicting_participants": writers}
        if share.permissions.allow_write and listeners:
            return {**common, "summary": "A transmitting participant cannot attach while a participant that requires a listen-only bus is attached.", "conflicting_participants": listeners}
        return None

    # -- detach ------------------------------------------------------------

    def _handle_detach(self, attached: _Attached) -> JsonObject:
        self._detach(attached, "requested")
        with self._guard:
            return {"ok": True, "message": "detached", "participant": attached.name, "attached_participants": sorted(self.participants)}

    def _detach(self, attached: _Attached, reason: str) -> None:
        stop = False
        with self._guard:
            if self.participants.get(attached.name) is attached:
                self.participants.pop(attached.name, None)
                self._log_bus({"event": "participant_detach", "bus_id": self.bus_id, "participant": attached.name, "reason": reason, "frames_used": attached.frames_used})
            stop = not self.participants and self.attach_total > 0
        if stop:
            self.stop("last_participant_detached")

    # -- requests ----------------------------------------------------------

    def _handle_request(self, attached: _Attached, kind: object, message: JsonObject) -> JsonObject:
        if kind == "status":
            with self._guard:
                return {"ok": True, "message": "bus_status", "bus_key": self.bus_key, "counter": self.counter, "broker_pid": os.getpid(), "attached_participants": sorted(self.participants), "bus_gated": self.bus_gated, "frames_seen": self.frame_seq}
        if kind == "incident":
            return self._handle_incident(attached, message)
        if kind == "poll_incident":
            with self._guard:
                return {"ok": True, "message": "incident_poll", "aborted": attached.abort is not None, "abort": attached.abort}
        blocked = self._blocked(attached)
        if blocked is not None:
            return blocked
        if kind == "send":
            return self._handle_send(attached, message)
        if kind == "read":
            return self._handle_read(attached, message)
        return {"ok": False, "error_type": "can_broker_invalid_message", "summary": "The CAN broker received a message it cannot read.", "message": kind}

    def _blocked(self, attached: _Attached) -> JsonObject | None:
        with self._guard:
            if attached.abort is None:
                return None
            scope = attached.abort.get("scope")
            return {
                "ok": False,
                "error_type": "can_bus_incident" if scope == "bus" else "can_participant_incident",
                "summary": "This CAN participant's run was aborted by a bus-scoped incident." if scope == "bus" else "This CAN participant's run was aborted by a participant-scoped incident.",
                "bus_id": self.bus_id,
                "participant": attached.name,
                "abort": attached.abort,
                "bus_gated": self.bus_gated,
                "retry_safe": False,
                "side_effect_committed": False,
            }

    def _handle_incident(self, attached: _Attached, message: JsonObject) -> JsonObject:
        scope = message.get("scope")
        if scope not in {"bus", "participant"}:
            return {"ok": False, "error_type": "invalid_argument", "summary": "A CAN incident scope must be 'bus' or 'participant'.", "scope": scope}
        reason = str(message.get("reason") or "unspecified")
        abort = {
            "scope": scope,
            "reason": reason,
            "detail": message.get("detail"),
            "recovery_action": self.config.recovery.auto_recover,
            "at": utc_now_iso(),
        }
        with self._guard:
            if scope == "bus":
                self.bus_gated = True
                self.bus_incident = abort
                for participant in self.participants.values():
                    participant.abort = abort
                aborted = sorted(self.participants)
            else:
                attached.abort = abort
                aborted = [attached.name]
            self._log_bus({"event": "incident", "bus_id": self.bus_id, "scope": scope, "reason": reason, "reported_by": attached.name, "aborted_participants": aborted, "bus_gated": self.bus_gated})
            return {"ok": True, "message": "incident_recorded", "scope": scope, "reason": reason, "bus_gated": self.bus_gated, "aborted_participants": aborted, "abort": abort}

    def _handle_send(self, attached: _Attached, message: JsonObject) -> JsonObject:
        from agentic_hil.can import CanFrame

        if not attached.share.permissions.allow_write:
            return {"ok": False, "error_type": "permission_denied", "summary": "Writing this CAN bus is disabled for this participant by the authoritative config.", "bus_id": self.bus_id, "participant": attached.name, "retry_safe": False, "side_effect_committed": False}
        wire = message.get("frame")
        if not wire_frame_valid(wire):
            return {"ok": False, "error_type": "invalid_argument", "summary": "The CAN broker received a frame it cannot read.", "participant": attached.name, "side_effect_committed": False}
        assert isinstance(wire, dict)
        if not filter_accepts(attached.share, int(wire["id"])):
            return {"ok": False, "error_type": "can_participant_filter_violation", "summary": "This CAN participant's view does not carry that identifier, so it may not send it.", "bus_id": self.bus_id, "participant": attached.name, "frame": wire, "view": share_view(attached.share), "retry_safe": False, "side_effect_committed": False}
        budget = self._spend_budget(attached)
        if budget is not None:
            return budget
        frame = CanFrame(id=int(wire["id"]), extended=bool(wire["extended"]), rtr=bool(wire["rtr"]), data=bytes.fromhex(str(wire["data_hex"])))
        try:
            sent = self.adapter_session.send(frame)  # type: ignore[union-attr]
        except BaseException as error:
            # The adapter itself raised: that is the bus, not this participant.
            return self._raise_bus_incident("can_adapter_send_raised", f"{type(error).__name__}: {error}")
        with self._guard:
            self.frame_seq += 1
            seq = self.frame_seq
            self._log_bus({"event": "frame", "seq": seq, "direction": "tx", "bus_id": self.bus_id, "participant": attached.name, "frame": wire, "ok": bool(sent.get("ok"))})
        if not sent.get("ok"):
            return {"ok": False, "error_type": "can_send_failed", "summary": str(sent.get("summary", "The CAN adapter failed to send a frame.")), "bus_id": self.bus_id, "participant": attached.name, "frame_seq": seq, "frame": wire, "backend_error": sent.get("backend_error"), "side_effect_status": "unknown"}
        return {"ok": True, "message": "sent", "frame_seq": seq, "participant": attached.name, "frame": wire, "frames_used": attached.frames_used, "max_frames": attached.share.max_frames}

    def _handle_read(self, attached: _Attached, message: JsonObject) -> JsonObject:
        if not attached.share.permissions.allow_read:
            return {"ok": False, "error_type": "permission_denied", "summary": "Reading this CAN bus is disabled for this participant by the authoritative config.", "bus_id": self.bus_id, "participant": attached.name, "retry_safe": False, "side_effect_committed": False}
        try:
            max_frames = int(message.get("max_frames") or 1)
            wait_timeout_s = float(message.get("wait_timeout_s") or 0.0)
        except (TypeError, ValueError):
            return {"ok": False, "error_type": "invalid_argument", "summary": "max_frames must be an integer and wait_timeout_s a number.", "participant": attached.name}
        if max_frames < 1 or max_frames > self.bus_config.max_buffer_frames:
            return {"ok": False, "error_type": "invalid_argument", "summary": "max_frames must be between 1 and the bus max_buffer_frames.", "max_buffer_frames": self.bus_config.max_buffer_frames, "participant": attached.name}
        with self._guard:
            pending = len(attached.queue)
        if pending < max_frames:
            drawn = self._draw_from_bus(min(self.bus_config.max_buffer_frames, max(max_frames, 1)), max(0.0, min(wait_timeout_s, self.bus_config.timeout_s, 60.0)))
            if drawn is not None:
                return drawn
        with self._guard:
            taken = attached.queue[:max_frames]
            del attached.queue[: len(taken)]
            attached.frames_used += len(taken)
            over = attached.frames_used > attached.share.max_frames
        if over:
            return self._budget_exhausted(attached)
        return {"ok": True, "message": "frames", "frames": taken, "frames_read": len(taken), "frames_used": attached.frames_used, "max_frames": attached.share.max_frames, "participant": attached.name}

    def _draw_from_bus(self, max_frames: int, wait_timeout_s: float) -> JsonObject | None:
        """Read the medium once and fan the frames out to every view that carries them.

        The broker is the only reader of the adapter, which is what makes the
        whole-bus log complete and what stops two participants from consuming
        each other's traffic: a read is destructive at the controller, so a
        per-participant read would have been one participant stealing frames."""
        from agentic_hil.can import normalize_received_frames

        try:
            read = self.adapter_session.read(max_frames, wait_timeout_s)  # type: ignore[union-attr]
        except BaseException as error:
            return self._raise_bus_incident("can_adapter_read_raised", f"{type(error).__name__}: {error}")
        if not read.get("ok"):
            return self._raise_bus_incident("can_adapter_read_failed", str(read.get("summary", "The CAN adapter failed to read.")))
        frames = normalize_received_frames(read.get("frames", []))
        if frames is None:
            return self._raise_bus_incident("can_adapter_invalid_response", "The CAN adapter returned malformed frame data.")
        with self._guard:
            for frame in frames:
                self.frame_seq += 1
                seq = self.frame_seq
                wire = {"id": int(frame["id"]), "extended": bool(frame["extended"]), "rtr": bool(frame["rtr"]), "data_hex": str(frame["data_hex"])}
                delivered = sorted(name for name, item in self.participants.items() if item.share.permissions.allow_read and filter_accepts(item.share, wire["id"]))
                self._log_bus({"event": "frame", "seq": seq, "direction": "rx", "bus_id": self.bus_id, "frame": wire, "delivered_to": delivered})
                for name in delivered:
                    self.participants[name].queue.append({**wire, "frame_seq": seq})
        return None

    def _spend_budget(self, attached: _Attached) -> JsonObject | None:
        with self._guard:
            if attached.frames_used >= attached.share.max_frames:
                return self._budget_exhausted(attached)
            attached.frames_used += 1
        return None

    def _budget_exhausted(self, attached: _Attached) -> JsonObject:
        abort = {"scope": "participant", "reason": "can_participant_frame_budget_exhausted", "detail": {"max_frames": attached.share.max_frames}, "recovery_action": self.config.recovery.auto_recover, "at": utc_now_iso()}
        with self._guard:
            attached.abort = abort
            self._log_bus({"event": "incident", "bus_id": self.bus_id, "scope": "participant", "reason": abort["reason"], "reported_by": attached.name, "aborted_participants": [attached.name], "bus_gated": self.bus_gated})
        return {"ok": False, "error_type": "can_participant_frame_budget_exhausted", "summary": "This CAN participant used its whole configured frame budget; its run is aborted and the bus keeps running.", "bus_id": self.bus_id, "participant": attached.name, "frames_used": attached.frames_used, "max_frames": attached.share.max_frames, "abort": abort, "retry_safe": False, "side_effect_committed": False}

    def _raise_bus_incident(self, reason: str, detail: object) -> JsonObject:
        abort = {"scope": "bus", "reason": reason, "detail": detail, "recovery_action": self.config.recovery.auto_recover, "at": utc_now_iso()}
        with self._guard:
            self.bus_gated = True
            self.bus_incident = abort
            for participant in self.participants.values():
                participant.abort = abort
            aborted = sorted(self.participants)
            self._log_bus({"event": "incident", "bus_id": self.bus_id, "scope": "bus", "reason": reason, "reported_by": "broker", "aborted_participants": aborted, "bus_gated": True})
        return {"ok": False, "error_type": "can_bus_incident", "summary": "A physical CAN bus incident aborted every participant's run and gated the bus.", "bus_id": self.bus_id, "abort": abort, "aborted_participants": aborted, "bus_gated": True, "retry_safe": False, "side_effect_committed": False}

    def _log_bus(self, event: JsonObject) -> None:
        if not self.bus_frame_log:
            return
        with suppress(ConfigError, OSError, ValueError):
            safe_append_text(self.bus_frame_log, json.dumps({"at": utc_now_iso(), **event}) + "\n")


