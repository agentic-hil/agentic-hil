# Frames on the wire.


def frame_to_wire(frame_id: int, data: bytes, *, extended: bool = False, rtr: bool = False) -> JsonObject:
    return {"id": int(frame_id), "extended": bool(extended), "rtr": bool(rtr), "data_hex": bytes(data).hex()}


def wire_frame_valid(value: object) -> bool:
    if not isinstance(value, dict) or set(value) != set(MESSAGE_SURFACE["frame"]):
        return False
    if not isinstance(value.get("id"), int) or isinstance(value.get("id"), bool):
        return False
    if not isinstance(value.get("extended"), bool) or not isinstance(value.get("rtr"), bool):
        return False
    data_hex = value.get("data_hex")
    if not isinstance(data_hex, str):
        return False
    try:
        bytes.fromhex(data_hex)
    except ValueError:
        return False
    maximum = 0x1FFFFFFF if value["extended"] else 0x7FF
    return 0 <= value["id"] <= maximum


def filter_accepts(share: CanShareConfig, frame_id: int) -> bool:
    """Whether a participant's view carries this identifier. No filter is every identifier."""
    if not share.filters:
        return True
    return any((frame_id & term.mask) == (term.identifier & term.mask) for term in share.filters)


def share_view(share: CanShareConfig) -> JsonObject:
    return {
        "filter": [{"id": term.identifier, "mask": term.mask, "extended": term.extended} for term in share.filters],
        "max_frames": share.max_frames,
        "requires_listen_only": share.requires_listen_only,
        "permissions": {"allow_read": share.permissions.allow_read, "allow_write": share.permissions.allow_write},
    }


def listen_only_proof(bus_config: CanBusConfig) -> str:
    """What a listen-only claim on this bus is, in one word.

    ``service`` enforcement is the broker declining to forward, which is software
    filtering and is named as such here and everywhere it is reported. It is
    never rendered as the controller proof, whatever the adapter is capable of:
    the point of the configuration key is that the two are not interchangeable."""
    return "controller" if bus_config.listen_only_enforcement == "controller" else "software_filter"


